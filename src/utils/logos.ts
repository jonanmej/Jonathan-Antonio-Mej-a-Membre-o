export const getLogoBase64 = (svgString: string): Promise<string> => {
  return new Promise((resolve) => {
    const widthMatch = svgString.match(/width="(\d+)"/);
    const heightMatch = svgString.match(/height="(\d+)"/);
    const originalWidth = widthMatch ? parseInt(widthMatch[1]) : 300;
    const originalHeight = heightMatch ? parseInt(heightMatch[1]) : 100;
    
    const scale = 4; // Higher scale for better resolution
    const scaledWidth = originalWidth * scale;
    const scaledHeight = originalHeight * scale;
    
    // Inject scaled width and height into the SVG string to preserve resolution
    let scaledSvg = svgString.replace(/width="\d+"/, `width="${scaledWidth}"`);
    scaledSvg = scaledSvg.replace(/height="\d+"/, `height="${scaledHeight}"`);

    const canvas = document.createElement('canvas');
    canvas.width = scaledWidth;
    canvas.height = scaledHeight;
    const ctx = canvas.getContext('2d');
    
    const img = new Image();
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(scaledSvg);
    
    img.onload = () => {
      // Draw at the new intrinsic size
      ctx?.drawImage(img, 0, 0, scaledWidth, scaledHeight);
      resolve(canvas.toDataURL('image/png', 1.0));
    };
    
    img.onerror = (e) => {
      console.error("Failed to load SVG into image", e);
      resolve('');
    };
  });
};
    